const patterns: Array<[RegExp, (part: string) => string]> = [
  [/^(\d+) 个工作表$/, n => `${n} ${n === '1' ? 'worksheet' : 'worksheets'}`],
  [/^图表 (\d+)$/, n => `Charts (${n})`],
  [/^组件 (\d+)$/, n => `Components (${n})`],
  [/^计数：(.+)$/, n => `Count: ${n}`],
  [/^已选 (.+) 格$/, n => `${n} cells selected`],
  [/^已去除 (\d+) 行重复数据$/, n => `Removed ${n} duplicate ${n === '1' ? 'row' : 'rows'}.`],
  [/^已导出 (.+)$/, name => `Exported ${name}`],
  [/^前往当前选区 (.+)$/, range => `Go to selection ${range}`],
  [/^数据来源 (.+)$/, range => `Source: ${range}`],
  [/^([A-Z]+) 列$/, column => `Column ${column}`],
  [/^(\d+) 行$/, row => `Row ${row}`],
  [/^删除「(.+)」及其中的单元格？$/, name => `Delete “${name}” and its cells?`],
  [/^已启用筛选 · (.+)$/, range => `Filter enabled · ${range}`],
  [/^表格引擎无法启动：(.+)$/, error => `Could not start the spreadsheet engine: ${error}`],
]

export function translateSpreadsheetCopy(key: string): string | undefined {
  if (Object.hasOwn(spreadsheetUiCopy, key)) return spreadsheetUiCopy[key]
  if (key.startsWith('平均值：')) return key.replace('平均值：', 'Average: ').replace('计数：', 'Count: ').replace('求和：', 'Sum: ')
  for (const [pattern, render] of patterns) {
    const match = pattern.exec(key)
    if (match) return render(match[1]!)
  }
}
