import {mkdtemp,mkdir,writeFile,readFile,rm} from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import {it,expect} from 'vitest'
import {createRequire} from 'node:module'
// Exercise the actual Node installer bytes; Vitest rewrites Function.toString().
const {syncProfileRuntimePatches,verifyProfileRuntimePatches}=createRequire(import.meta.url)('../scripts/lib/profile-runtime-patches.mjs')
const {patchOpenAIResponsesToolOptionals}=createRequire(import.meta.url)('../scripts/lib/openai-responses-tool-optionals.mjs')
it('ships patched runtime into the independent plugin profile and verifies parity',async()=>{
 const root=await mkdtemp(path.join(os.tmpdir(),'profile-patches-'))
 try{
  for(const name of ['dsh-agent-loop','dsh-llm','dsh-tool-fs','dsh-subagent','dsh-skill','dsh-message-feedback','dsh-tool-bash','dsh-tool-todo','dsh-plan-mode','dsh-tool-goal']){
   const source=JSON.parse(await readFile(`node_modules/@deepseek-ai/${name}/package.json`,'utf8'))
   const dir=path.join(root,'node_modules/@deepseek-ai',name)
   await mkdir(path.join(dir,'lib'),{recursive:true})
   await writeFile(path.join(dir,'package.json'),JSON.stringify({version:source.version}))
   await writeFile(path.join(dir,'lib/index.js'),'unpatched')
  }
  const nested=path.join(root,'node_modules/.pnpm/@deepseek-ai+dsh-skill@0.1.0-rc.7_peer/node_modules/@deepseek-ai/dsh-skill')
  await mkdir(path.join(nested,'lib'),{recursive:true})
  await writeFile(path.join(nested,'package.json'),JSON.stringify({version:'0.1.0-rc.7'}))
  await writeFile(path.join(nested,'lib/index.js'),'unpatched nested copy')
  const nestedBash=path.join(root,'node_modules/.pnpm/@deepseek-ai+dsh-tool-bash@0.1.0-rc.7_peer/node_modules/@deepseek-ai/dsh-tool-bash')
  await mkdir(path.join(nestedBash,'lib'),{recursive:true})
  await writeFile(path.join(nestedBash,'package.json'),JSON.stringify({version:'0.1.0-rc.7'}))
  await writeFile(path.join(nestedBash,'lib/index.js'),'unpatched nested bash copy')
  const nestedPlan=path.join(root,'node_modules/.pnpm/@deepseek-ai+dsh-plan-mode@0.1.0-rc.7_peer/node_modules/@deepseek-ai/dsh-plan-mode')
  await mkdir(path.join(nestedPlan,'lib'),{recursive:true})
  await writeFile(path.join(nestedPlan,'package.json'),JSON.stringify({version:'0.1.0-rc.7'}))
  await writeFile(path.join(nestedPlan,'lib/index.js'),'unpatched nested plan copy')
  const nestedGoal=path.join(root,'node_modules/.pnpm/@deepseek-ai+dsh-tool-goal@0.1.0-rc.7_peer/node_modules/@deepseek-ai/dsh-tool-goal')
  await mkdir(path.join(nestedGoal,'lib'),{recursive:true})
  await writeFile(path.join(nestedGoal,'package.json'),JSON.stringify({version:'0.1.0-rc.7'}))
  await writeFile(path.join(nestedGoal,'lib/index.js'),'unpatched nested goal policy')
  const piName='@earendil-works/pi-ai',piEntry='dist/api/openai-responses.js'
  const piVersion=JSON.parse(await readFile(`node_modules/${piName}/package.json`,'utf8')).version
  const piTargets=[path.join(root,'node_modules',piName),path.join(root,'node_modules/.pnpm',`@earendil-works+pi-ai@${piVersion}`,'node_modules',piName)]
  for(const target of piTargets){
   await mkdir(path.join(target,'dist/api'),{recursive:true})
   await writeFile(path.join(target,'package.json'),JSON.stringify({version:piVersion}))
   await writeFile(path.join(target,piEntry),'unpatched provider')
  }
  await expect(verifyProfileRuntimePatches(process.cwd(),path.join(root,'node_modules'))).rejects.toThrow()
  const digest=await syncProfileRuntimePatches(process.cwd(),root)
  const expectedProvider=patchOpenAIResponsesToolOptionals(await readFile(`node_modules/${piName}/${piEntry}`,'utf8'))
  for(const target of piTargets)expect(await readFile(path.join(target,piEntry),'utf8')).toBe(expectedProvider)
  expect(await readFile(path.join(root,'node_modules/@deepseek-ai/dsh-subagent/lib/index.js'),'utf8')).toContain('CANVAS_TASK_OWNED_SETTLEMENT')
  expect(await readFile(path.join(root,'node_modules/@deepseek-ai/dsh-message-feedback/lib/index.js'),'utf8')).toContain('ework:note-feedback-target:v1')
  expect(await readFile(path.join(root,'node_modules/@deepseek-ai/dsh-skill/lib/index.js'),'utf8')).toContain('registerCandidatePolicy(policy)')
  expect(await readFile(path.join(nested,'lib/index.js'),'utf8')).toContain('registerCandidatePolicy(policy)')
  const bash=await readFile(path.join(root,'node_modules/@deepseek-ai/dsh-tool-bash/lib/index.js'),'utf8')
  expect(bash).toContain('kind: args.background_kind==="service"?"bash-service":"bash"')
  expect(await readFile(path.join(nestedBash,'lib/index.js'),'utf8')).toBe(bash)
  const plan=await readFile(path.join(root,'node_modules/@deepseek-ai/dsh-plan-mode/lib/index.js'),'utf8')
  expect(plan).toContain('sherlock:plan-pending-replay:rc7:v1')
  expect(await readFile(path.join(nestedPlan,'lib/index.js'),'utf8')).toBe(plan)
  expect(await readFile(path.join(root,'node_modules/@deepseek-ai/dsh-tool-todo/lib/index.js'),'utf8')).toContain('task-progress-continuation:v5')
  const goal=await readFile(path.join(root,'node_modules/@deepseek-ai/dsh-tool-goal/lib/index.js'),'utf8')
  expect(goal).toContain('sherlock:goal-tool-stage-guidance:rc7:v1')
  expect(await readFile(path.join(nestedGoal,'lib/index.js'),'utf8')).toBe(goal)
  expect(await readFile(path.join(root,'node_modules/@deepseek-ai/dsh-agent-loop/lib/index.js'),'utf8')).toContain('sherlock:human-steering-yield:rc7:v1')
  expect(digest).toMatch(/^[a-f0-9]{64}$/)
  expect(await syncProfileRuntimePatches(process.cwd(),root)).toBe(digest)
  expect(await readFile(path.join(nestedPlan,'lib/index.js'),'utf8')).toBe(plan)
  await verifyProfileRuntimePatches(process.cwd(),path.join(root,'node_modules'))
  await writeFile(path.join(nestedPlan,'lib/index.js'),'plan replay was dropped')
  await expect(verifyProfileRuntimePatches(process.cwd(),path.join(root,'node_modules'))).rejects.toThrow(/parity/)
  await syncProfileRuntimePatches(process.cwd(),root)
  expect(await readFile(path.join(nestedPlan,'lib/index.js'),'utf8')).toBe(plan)
  await writeFile(path.join(nestedPlan,'package.json'),JSON.stringify({version:'99'}))
  await expect(syncProfileRuntimePatches(process.cwd(),root)).rejects.toThrow(/version/)
  await writeFile(path.join(nestedPlan,'package.json'),JSON.stringify({version:'0.1.0-rc.7'}))
  await writeFile(path.join(piTargets[1],piEntry),'provider patch was dropped')
  await expect(verifyProfileRuntimePatches(process.cwd(),path.join(root,'node_modules'))).rejects.toThrow(/parity/)
  await syncProfileRuntimePatches(process.cwd(),root)
  await writeFile(path.join(nested,'lib/index.js'),'policy was dropped')
  await expect(verifyProfileRuntimePatches(process.cwd(),path.join(root,'node_modules'))).rejects.toThrow(/parity/)
  await syncProfileRuntimePatches(process.cwd(),root)
  await rm(path.join(root,'node_modules/@deepseek-ai/dsh-tool-fs'),{recursive:true})
  await syncProfileRuntimePatches(process.cwd(),root)
  await verifyProfileRuntimePatches(process.cwd(),path.join(root,'node_modules'))
  expect(await readFile(path.join(root,'node_modules/@deepseek-ai/dsh-llm/lib/index.js'),'utf8')).toContain('toolImagesAsText')
  await writeFile(path.join(nestedBash,'lib/index.js'),'service lifecycle was dropped')
  await expect(verifyProfileRuntimePatches(process.cwd(),path.join(root,'node_modules'))).rejects.toThrow(/parity/)
  await syncProfileRuntimePatches(process.cwd(),root)
  expect(await readFile(path.join(nestedBash,'lib/index.js'),'utf8')).toBe(bash)
  await writeFile(path.join(nestedGoal,'lib/index.js'),'goal stage policy was dropped')
  await expect(verifyProfileRuntimePatches(process.cwd(),path.join(root,'node_modules'))).rejects.toThrow(/parity/)
  await syncProfileRuntimePatches(process.cwd(),root)
  expect(await readFile(path.join(nestedGoal,'lib/index.js'),'utf8')).toBe(goal)
  await writeFile(path.join(nestedGoal,'package.json'),JSON.stringify({version:'99'}))
  await expect(syncProfileRuntimePatches(process.cwd(),root)).rejects.toThrow(/version/)
  await writeFile(path.join(nestedGoal,'package.json'),JSON.stringify({version:'0.1.0-rc.7'}))
  await writeFile(path.join(nestedBash,'package.json'),JSON.stringify({version:'99'}))
  await expect(syncProfileRuntimePatches(process.cwd(),root)).rejects.toThrow(/version/)
  await writeFile(path.join(nestedBash,'package.json'),JSON.stringify({version:'0.1.0-rc.7'}))
  await writeFile(path.join(root,'node_modules/@deepseek-ai/dsh-llm/package.json'),JSON.stringify({version:'99'}))
  await expect(syncProfileRuntimePatches(process.cwd(),root)).rejects.toThrow(/version/)
 }finally{await rm(root,{recursive:true,force:true})}
})
