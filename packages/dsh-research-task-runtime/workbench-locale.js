export function workbenchText(value,locale=typeof document==='undefined'?'zh':document.documentElement.dataset.odysseyLocale) {
 if(locale!=='en'||typeof value!=='string')return value
 if(Object.hasOwn(WORKBENCH_ENGLISH,value))return WORKBENCH_ENGLISH[value]
 return value.replace(/^近 (\d+) 根$/, 'Last $1 bars').replace(/^按(.+)排序$/, 'Sort by $1').replace(/^(\d+ \/ \d+) 行$/, '$1 rows').replace(/^(\d+ \/ \d+) 条$/, '$1 items').replace(/^已整理 (\d+) 个组件$/, 'Arranged $1 components').replace(/^已更新 (\d+) 个组件$/, 'Updated $1 components').replace(/^已复制 (\d+) 个组件$/, 'Copied $1 components').replace(/^已粘贴 (\d+) 个组件$/, 'Pasted $1 components').replace(/^已移除 (\d+) 个组件$/, 'Removed $1 components').replace(/^已写入 (\d+) 个数据字段，正在校验内容$/, 'Wrote $1 data fields; validating content').replace(/^基于所选 (\d+) 个组件$/, (_,n)=>`Based on ${n} selected component${n==='1'?'':'s'}`).replace(/^来源：(\d+) 个组件$/, (_,n)=>`Sources: ${n} component${n==='1'?'':'s'}`).replace(/^每 (\d+) (分钟|小时)$/,(_,n,unit)=>`Every ${n} ${unit==='分钟'?'minute':'hour'}${n==='1'?'':'s'}`).replace(/^打开来源：/, 'Open source: ').replace(/（离线交互网页）$/, ' (offline interactive page)')
}
