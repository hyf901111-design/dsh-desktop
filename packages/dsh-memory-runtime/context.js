const states = {
  available: '本轮已提供可用的记忆原文，只能据此使用对应事实。',
  empty: '本轮已完成记忆核对，没有能直接支持当前请求的记忆。',
  disabled: '本轮记忆已停用，不读取或自动保存长期记忆，也不要声称已经记住。',
  unavailable: '本轮记忆暂不可用，不代表用户从未提供过信息。'
}

export function memoryRequestPolicy(status, autoEnabled) {
  const capture = autoEnabled && (status === 'available' || status === 'empty')
    ? '自动记录已开启，应用会在回答结束后异步整理用户明确的新偏好和约定，无需你调用工具写入。不要声称不能保存长期记忆或要求用户每次重复；写入尚未确认时也不要宣称已经保存。'
    : ''
  return `[ework-memory-status:${status}]\n${states[status]}\n${capture}\n长期记忆由应用提供，不需要也不得自行搜索或读取应用内部记忆文件、数据库、历史会话或其他账户数据来补全答案。询问用户或项目的既有事实、偏好、约定时，若当前对话和本轮提供的记忆没有答案，直接简短说明目前没有可用记录或无法确定。此时不要猜测，不调用文件、终端或搜索工具寻找这个缺失答案，包括先搜索一次工作区；工作区中碰巧存在的其他项目资料不能补成当前项目的记忆。只有用户明确要求查找资料或指定文件时，才在其指定范围正常查找。常识问答、翻译、写作、编程等正常任务照常完成。当前用户要求优先，不把临时要求当长期偏好，不把助手自己推断的内容当记忆。普通回答不必解释这些内部机制。`
}
